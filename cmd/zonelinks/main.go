// Command zonelinks writes helpers/zoneLinks.go, the zone database's other
// names for its zones, from a tzdata.zi file's link lines ("L zone link"):
//
//	go run ./cmd/zonelinks /usr/share/zoneinfo/tzdata.zi > helpers/zoneLinks.go
//
// Run it on the newest tzdata to hand when the database adds or renames a
// zone; helpers' TestZoneLinksAgreeWithGoData checks each link against Go's
// own copy of the database.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: zonelinks path/to/tzdata.zi")
		os.Exit(2)
	}
	f, err := os.Open(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	version, links := "unknown", map[string]string{}
	lines := bufio.NewScanner(f)
	for lines.Scan() {
		fields := strings.Fields(lines.Text())
		switch {
		case len(fields) == 3 && fields[0] == "#" && fields[1] == "version":
			version = fields[2]
		case len(fields) == 3 && fields[0] == "L":
			links[fields[2]] = fields[1]
		}
	}
	if err := lines.Err(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	names := make([]string, 0, len(links))
	for link := range links {
		names = append(names, link)
	}
	sort.Strings(names)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./cmd/zonelinks %s; DO NOT EDIT.\n", os.Args[1])
	fmt.Fprintf(&b, "// From tzdata %s.\n\npackage helpers\n\n", version)
	b.WriteString("// zoneLinks is each of the zone database's other names for a zone (a\n")
	b.WriteString("// link: \"Europe/Kiev\") and the zone it names (\"Europe/Kyiv\").\n")
	b.WriteString("var zoneLinks = map[string]string{\n")
	for _, link := range names {
		zone := links[link]
		// A link to a link names the zone at the end of the chain.
		for seen := 0; seen < len(links); seen++ {
			next, ok := links[zone]
			if !ok {
				break
			}
			zone = next
		}
		fmt.Fprintf(&b, "\t%q: %q,\n", link, zone)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	os.Stdout.Write(out)
}
